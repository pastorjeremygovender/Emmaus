/**
 * Return the editorial heading for a Bible chapter.
 * Falls back to the generic "Chapter N" label when a heading has not been
 * curated for this book (should never happen for all 66 canon books).
 */
export function getChapterHeading(bookId: string, chapter: number): string {
  return ALL_CHAPTER_HEADINGS[bookId]?.[chapter] ?? `Chapter ${chapter}`;
}

